$ng = 0
foreach ($c in $cases) {
  $r = Get-StopCase $c.t
  $mark = "ok  "
  if ($r -ne $c.e) { $mark = "NG  "; $ng++ }
  $head = $c.t
  if ($head.Length -gt 46) { $head = $head.Substring(0, 46) + "…" }
  "{0}期待={1,-8} 実際={2,-8} {3}" -f $mark, $c.e, $r, $head
}
""
if ($ng -eq 0) { "全 {0} 件 合格" -f $cases.Count }
else { "全 {0} 件中 {1} 件 不合格" -f $cases.Count, $ng; exit 1 }
