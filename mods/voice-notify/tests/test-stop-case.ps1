  @{ e = "ask";  t = "ワークスペースの移動を確認し、実行時に壊れるハードコード3箇所を新パスへ修正しました。次のステップの番号をお選びください。" },
  @{ e = "ask";  t = "音声サンプルのセッションを特定しました。移動によりOneDriveの問題は解消しています。履歴ごと再開するか、このまま続行するかどちらにしますか。" },
